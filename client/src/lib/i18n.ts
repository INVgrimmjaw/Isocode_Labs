export type Locale = 'en' | 'hi';

const STORAGE_KEY = 'peti.locale';

export const locale = createStore<Locale>(storage.read<Locale>(STORAGE_KEY) ?? 'en');

export function setLocale(next: Locale) {
  storage.write(STORAGE_KEY, next);
  document.documentElement.lang = next;
  locale.set(next);
}

document.documentElement.lang = locale.get();

export type Translate = (key: StringKey, vars?: Record<string, string | number>) => string;

export function translate(key: StringKey, vars?: Record<string, string | number>): string {
  const template = (locale.get() === 'hi' ? hi : en)[key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ''));
}

/** Subscribes the calling component, so it re-renders when the language changes. */
export function useT(): Translate {
  locale.use();
  return translate;
}

const CATEGORY_HI: Record<string, string> = {
  Biscuits: 'बिस्कुट',
  Tea: 'चाय',
  Snacks: 'नमकीन',
  Laundry: 'कपड़े धोना',
  'Home care': 'घर की सफ़ाई',
};

export const itemCount = (count: number) =>
  count === 1 ? translate('bar.item') : translate('bar.items', { count });

export const caseCount = (count: number) =>
  count === 1 ? translate('cart.oneCase') : translate('cart.casesCount', { count });

export function categoryName(category: string): string {
  return locale.get() === 'hi' ? (CATEGORY_HI[category] ?? category) : category;
}
